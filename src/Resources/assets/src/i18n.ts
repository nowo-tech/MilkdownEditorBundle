/** Returns the message for `key`, with `{placeholders}` replaced. */
export function translate(messages: Messages, key: string, params: Record<string, string | number> = {}): string {
  const template = messages[key] ?? DEFAULT_MESSAGES[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole));
}
