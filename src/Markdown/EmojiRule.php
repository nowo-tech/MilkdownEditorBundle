    public const MAX_BYTES       = 64;
    public const MAX_CODE_POINTS = 8;

    /**
     * Whether `value` is an emoji (sequence) accepted as a callout icon.
     */
    public static function matches(string $value): bool
    {
        if ($value === '' || strlen($value) > self::MAX_BYTES) {
            return false;
        }
        $chars = preg_split('//u', $value, -1, PREG_SPLIT_NO_EMPTY);
        if ($chars === false || count($chars) > self::MAX_CODE_POINTS) {
            return false;
        }
        $cps = [];
        foreach ($chars as $char) {
            $cps[] = mb_ord($char, 'UTF-8');
        }
        $n = count($cps);
        $i = 0;
        while (true) {
            $cp = $cps[$i] ?? 0;
            if (self::isRegional($cp)) {
                if (!self::isRegional($cps[$i + 1] ?? 0)) {
                    return false;
                }
                $i += 2;
            } elseif (($cp >= 0x30 && $cp <= 0x39) || $cp === 0x23 || $cp === 0x2A) {
                ++$i;
                if (($cps[$i] ?? 0) === 0xFE0F) {
                    ++$i;
                }
                if (($cps[$i] ?? 0) !== 0x20E3) {
                    return false;
                }
                ++$i;
            } elseif (self::isPictographic($cp)) {
                ++$i;
                $next = $cps[$i] ?? 0;
                if ($next >= 0x1F3FB && $next <= 0x1F3FF) {
                    ++$i;
                }
                if (($cps[$i] ?? 0) === 0xFE0F) {
                    ++$i;
                }
            } else {
                return false;
            }
            if ($i === $n) {
                return true;
            }
            if (($cps[$i] ?? 0) !== 0x200D || $i + 1 === $n) {
                return false;
            }
            ++$i;
        }
    }

    private static function isRegional(int $cp): bool
    {
        return $cp >= 0x1F1E6 && $cp <= 0x1F1FF;
    }

    private static function isPictographic(int $cp): bool
    {
        $lo = 0;
        $hi = intdiv(count(self::PICTOGRAPHIC), 2) - 1;
        while ($lo <= $hi) {
            $mid = intdiv($lo + $hi, 2);
            if ($cp < self::PICTOGRAPHIC[$mid * 2]) {
                $hi = $mid - 1;
            } elseif ($cp > self::PICTOGRAPHIC[$mid * 2 + 1]) {
                $lo = $mid + 1;
            } else {
                return true;
            }
        }

        return false;
    }
}
