/**
 * Which callout `icon` values are emoji (1.7, audit DY-L1 / DY-I1): a linear scan of at most 8 code points with no
 * backtracking regex, the same table and steps as the editor (`dialect/emoji-rule.ts`). One or more emoji joined by
 * ZWJ (U+200D), each being an Extended_Pictographic code point (then an optional skin tone and VS16), a flag (two
